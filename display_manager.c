#include "codexion.h"

const char	*get_color_for_coder(int coder_id)
{
	static const char	*colors[] = {
		"\033[31m",
		"\033[32m",
		"\033[33m",
		"\033[34m",
		"\033[35m",
		"\033[36m",
		"\033[37m",
		"\033[91m",
		"\033[92m",
		"\033[93m",
		"\033[94m",
		"\033[95m",
		"\033[96m"
	};

	return (colors[(coder_id - 1) % 13]);
}
